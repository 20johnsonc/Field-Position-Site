def slugify_t(name): return re.sub(r'[^a-z0-9]+', '-', str(name).lower()).strip('-')
def _clean_nan(v):
    if v is None: return None
    if isinstance(v, dict): return {k: _clean_nan(x) for k, x in v.items()}
    if isinstance(v, (list, tuple)): return [_clean_nan(x) for x in v]
    if isinstance(v, bool): return v
    try: f = float(v)
    except (TypeError, ValueError): return v
    if math.isnan(f) or math.isinf(f): return None
    if f.is_integer(): return int(f)
    return f

