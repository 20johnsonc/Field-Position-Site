class BPRObs: pass
def build_obs(season, extra_pids=(), extra_teams=None):
    extra_teams = extra_teams or {}
    store = PBP.get(season, {})
    if not store: raise ValueError(f'No PBP for {season}')
    games = [(gid, rec) for gid, rec in store.items() if rec.get('stints') and rec.get('poss') and rec.get('total_seconds', 0) > 0]
    games.sort(key=lambda x: str(x[0]))
    all_pids = set(str(p) for p in extra_pids)
    all_teams = set()
    for gid, rec in games:
        all_teams.add(rec['home']); all_teams.add(rec['away'])
        for k in (rec.get('names') or {}): all_pids.add(str(k))
    for p, t in extra_teams.items():
        all_pids.add(str(p))
        if t: all_teams.add(t)
    pids = sorted(all_pids); teams = sorted(all_teams)
    pidx = {p: i for i, p in enumerate(pids)}
    player_team, names = {}, {}
    off_l, dfn_l, y_l, w_l, h_l, gid_l, gih_l = [], [], [], [], [], [], []
    games_meta, game_final = [], []
    seen_gids = {}
    for gid, rec in games:
        pps = rec['poss'] / rec['total_seconds']
        hv = 0.0 if rec.get('neutral') else 1.0
        fh, fa = 0.0, 0.0
        for st in rec['stints']:
            fh = max(fh, st[5] + st[3]); fa = max(fa, st[6] + st[4])
        if gid not in seen_gids:
            seen_gids[gid] = len(games_meta)
            games_meta.append(gid); game_final.append((fh, fa))
        gidx = seen_gids[gid]
        for st in rec['stints']:
            hids, aids, sec, hp, ap, h0, a0 = st
            if max(abs(h0-a0), abs((h0+hp)-(a0+ap))) > GARBAGE_MARGIN: continue
            poss = sec * pps
            if poss < 1.0: continue
            hi = [pidx[str(x)] for x in hids if str(x) in pidx]
            ai = [pidx[str(x)] for x in aids if str(x) in pidx]
            if len(hi) != 5 or len(ai) != 5: continue
            off_l.append(hi); dfn_l.append(ai); y_l.append(100*hp/poss); w_l.append(poss)
            h_l.append(hv); gid_l.append(gidx); gih_l.append(1)
            off_l.append(ai); dfn_l.append(hi); y_l.append(100*ap/poss); w_l.append(poss)
            h_l.append(0.0); gid_l.append(gidx); gih_l.append(0)
        for pid_raw, team in (rec.get('teams') or {}).items():
            if str(pid_raw) in pidx: player_team[pidx[str(pid_raw)]] = team
        for pid_raw, nm in (rec.get('names') or {}).items():
            if str(pid_raw) in pidx: names[pidx[str(pid_raw)]] = nm
    for p_raw in extra_pids:
        p = str(p_raw)
        if p not in pidx: continue
        i = pidx[p]
        if p in extra_teams and extra_teams[p]: player_team[i] = extra_teams[p]
        if i not in names and (season - 1) in POST:
            prev = POST[season - 1]
            if p in prev.index and 'name' in prev.columns: names[i] = prev.at[p, 'name']
    o = BPRObs()
    o.season = season; o.P = len(pids); o.T = len(teams)
    o.pids = pids; o.teams = teams; o.pidx = pidx
    o.player_team = player_team; o.names = names
    o.off = np.array(off_l, dtype=np.int32); o.dfn = np.array(dfn_l, dtype=np.int32)
    o.y = np.array(y_l, dtype=np.float64); o.w = np.array(w_l, dtype=np.float64)
    o.h = np.array(h_l, dtype=np.float64); o.game_idx = np.array(gid_l, dtype=np.int32)
    o.is_home = np.array(gih_l, dtype=np.int32)
    o.n_rows = len(off_l); o.game_ids = games_meta
    o.game_final = np.array(game_final, dtype=np.float64); o.n_games = len(games_meta)
    return o

def _design(obs, rows_idx=None):
    off = obs.off if rows_idx is None else obs.off[rows_idx]
    dfn = obs.dfn if rows_idx is None else obs.dfn[rows_idx]
    h = obs.h if rows_idx is None else obs.h[rows_idx]
    n = len(off); P = obs.P
    r = np.concatenate([np.repeat(np.arange(n), 5), np.repeat(np.arange(n), 5), np.arange(n), np.arange(n)])
    c = np.concatenate([off.ravel(), P + dfn.ravel(), np.full(n, 2*P), np.full(n, 2*P+1)])
    v = np.concatenate([np.ones(5*n), -np.ones(5*n), np.ones(n), h])
    return sparse.csr_matrix((v, (r, c)), shape=(n, 2*P+2))

def _norm_eq(obs, rows_idx=None):
    X = _design(obs, rows_idx)
    w = obs.w if rows_idx is None else obs.w[rows_idx]
    y = obs.y if rows_idx is None else obs.y[rows_idx]
    XtW = X.T @ sparse.diags(w)
    return (XtW @ X).tocsr(), XtW @ y

def _norm_eq_weighted(obs, idx, w):
    X = _design(obs, idx)
    XtW = X.T @ sparse.diags(w)
    return (XtW @ X).tocsr(), XtW @ obs.y[idx]

def _poss_counts(obs, idx, raw_w):
    P = obs.P
    po = np.bincount(obs.off[idx].ravel(), weights=np.repeat(raw_w, 5), minlength=P)
    pd_ = np.bincount(obs.dfn[idx].ravel(), weights=np.repeat(raw_w, 5), minlength=P)
    return po, pd_

def _solve(A, b, P, mu, pv, poss=None, K=TAU_POSS_K, sigma2=SIGMA2_FIXED):
    if poss is not None: pv_eff = pv * (poss + 1.0) / (poss + 1.0 + K)
    else: pv_eff = pv
    ridge = np.zeros(2*P+2)
    ridge[:2*P] = sigma2 / np.maximum(pv_eff, 1e-3)
    ridge[2*P]   = sigma2 / (INTERCEPT_PRIOR_SD**2)
    ridge[2*P+1] = sigma2 / (HCA_PRIOR_SD**2)
    mu_full = np.concatenate([mu, [INTERCEPT_PRIOR_MEAN, HCA_PRIOR_MEAN]])
    K_mat = (A + sparse.diags(ridge)).tocsr()
    M = sparse.diags(1.0 / np.maximum(K_mat.diagonal(), 1e-12))
    x, info = cg(K_mat, b + ridge*mu_full, M=M, rtol=1e-8, atol=0.0, maxiter=3000)
    return x

def _box_features(season):
    rows = RAW_STATS.get(season, [])
    if not rows: return pd.DataFrame()
    df = pd.DataFrame(rows)
    df['pid'] = df['athleteId'].astype(str)
    df = df.drop_duplicates('pid').set_index('pid')
    def _num(c): return pd.to_numeric(df[c], errors='coerce') if c in df.columns else pd.Series(np.nan, index=df.index, dtype=float)
    mins = _num('minutes').fillna(0)
    poss = (mins * 1.4).clip(lower=1)
    feats = {'min_share': mins/40.0, 'usage': _num('usage')/100.0}
    for c in ['pts','ast','tov','stl','blk','orb','drb','fta','fg3a','fg2a']:
        feats[c+'_per100'] = _num(c) / poss * 100
    for c in ['ts','ftr','efg','orb_pct']: feats[c] = _num(c)
    X = pd.DataFrame(feats, index=df.index); X['poss'] = poss
    return X[X['poss'] >= BOX_MIN_POSS]

def _predict_box(season, model):
    if model is None: return pd.Series(dtype=float)
    B = _box_features(season)
    if B.empty: return pd.Series(dtype=float)
    X = B.reindex(columns=model['cols']).values
    raw = pd.Series(X @ model['beta'], index=B.index)
    poss = B['poss'].clip(lower=1)
    valid = raw.dropna()
    if valid.empty: return pd.Series(np.nan, index=B.index, dtype=float)
    v_poss = poss.loc[valid.index]
    center = float(np.average(valid.values, weights=v_poss.values))
    rel = poss / (poss + BOX_REL_K)
    shrunk = rel * raw + (1 - rel) * center
    return shrunk.clip(-BOX_CLIP, BOX_CLIP)

def _train_box(seasons, side='o'):
    key = (tuple(sorted(seasons)), side)
    if key in _BOX_CACHE: return _BOX_CACHE[key]
    Xs, ys, ws = [], [], []
    for s in seasons:
        try: obs = build_obs(s)
        except: continue
        A, b = _norm_eq(obs)
        x = _solve(A, b, obs.P, np.zeros(2*obs.P), np.full(2*obs.P, 100.0))
        coef = x[:obs.P] if side=='o' else x[obs.P:2*obs.P]
        df_coef = pd.Series(coef, index=obs.pids)
        B = _box_features(s)
        if B.empty: continue
        common = B.index.intersection(df_coef.index)
        if len(common) < 50: continue
        Xs.append(B.loc[common].drop(columns=['poss']).values)
        ys.append(df_coef.loc[common].values)
        ws.append(B.loc[common, 'poss'].values)
    if not Xs: _BOX_CACHE[key] = None; return None
    X = np.vstack(Xs); y = np.concatenate(ys); w = np.concatenate(ws)
    wn = w/w.mean()
    XtX = (X*wn[:,None]).T @ X; Xty = (X*wn[:,None]).T @ y
    beta = np.linalg.solve(XtX + np.eye(X.shape[1])*BOX_RIDGE, Xty)
    result = dict(beta=beta, cols=B.columns.drop('poss').tolist())
    _BOX_CACHE[key] = result
    return result

