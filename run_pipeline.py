def _dig(d, *path):
    for k in path:
        if not isinstance(d, dict) or d.get(k) is None: return None
        d = d[k]
    return d

def _num1(x):
    try: f = float(x); return f if np.isfinite(f) else None
    except: return None

def _side_totals(stats):
    if not isinstance(stats, dict): return None
    fgm, fga = _num1(_dig(stats, 'fieldGoals', 'made')), _num1(_dig(stats, 'fieldGoals', 'attempted'))
    tpm, fta = _num1(_dig(stats, 'threePointFieldGoals', 'made')), _num1(_dig(stats, 'freeThrows', 'attempted'))
    orb, drb = _num1(_dig(stats, 'rebounds', 'offensive')), _num1(_dig(stats, 'rebounds', 'defensive'))
    tov = _num1(_dig(stats, 'turnovers', 'total')) or _num1(stats.get('turnovers'))
    if None in (fgm, fga, tpm, fta, orb, drb, tov): return None
    return dict(fgm=fgm, fga=fga, tpm=tpm, fta=fta, orb=orb, drb=drb, tov=tov)

def _team_four_factors(season):
    keys = ('fgm', 'fga', 'tpm', 'fta', 'orb', 'drb', 'tov'); agg = {}
    for r in _load_game_teams(season):
        team = r.get('team'); me = _side_totals(r.get('teamStats')); op = _side_totals(r.get('opponentStats'))
        if not team or me is None or op is None: continue
        a = agg.setdefault(team, {f'{s}_{k}': 0.0 for s in ('me', 'op') for k in keys})
        for k in keys: a[f'me_{k}'] += me[k]; a[f'op_{k}'] += op[k]
    if not agg: return pd.DataFrame()
    out = {}
    for t, a in agg.items():
        out[t] = dict(efg=(a['me_fgm'] + 0.5*a['me_tpm']) / max(a['me_fga'], 1), tov_rate=a['me_tov'] / max(a['me_fga'] + 0.44*a['me_fta'] + a['me_tov'], 1),
                      orb_pct=a['me_orb'] / max(a['me_orb'] + a['op_drb'], 1), ftr=a['me_fta'] / max(a['me_fga'], 1),
                      opp_efg=(a['op_fgm'] + 0.5*a['op_tpm']) / max(a['op_fga'], 1), opp_tov_rate=a['op_tov'] / max(a['op_fga'] + 0.44*a['op_fta'] + a['op_tov'], 1),
                      opp_orb_pct=a['op_orb'] / max(a['op_orb'] + a['me_drb'], 1), opp_ftr=a['op_fta'] / max(a['op_fga'], 1))
    return pd.DataFrame(out).T

