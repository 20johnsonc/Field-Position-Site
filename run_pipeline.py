def apply_display_scale(td, scale):
    obpr, dbpr = td['team_obpr'].fillna(0) - td['team_obpr'].mean(), td['team_dbpr'].fillna(0) - td['team_dbpr'].mean()
    td['adj_off'] = 105.0 + scale * obpr; td['adj_def'] = 105.0 - scale * dbpr; td['adj_net'] = scale * (obpr + dbpr)
    return td

