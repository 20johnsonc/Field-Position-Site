def cbbd_get(path, params=None, retries=4, timeout=90):
    h = {'Authorization': f'Bearer {CBBD_API_KEY}', 'Accept': 'application/json'}
    for a in range(retries):
        try:
            r = _sess.get(CBBD_BASE + path, params=params, headers=h, timeout=timeout)
            if r.status_code in (429, 500, 502, 503, 504):
                time.sleep(2**a); continue
            if r.status_code != 200:
                raise RuntimeError(f'{path} {r.status_code}')
            return r.json()
        except requests.RequestException:
            time.sleep(2**a)
    raise RuntimeError(f'{path} failed after {retries} retries')

