def build_preseason_prior(season, obs, box_o, box_d, verbose=True):
    box_po = _predict_box(season, box_o) if box_o else pd.Series(dtype=float)
    box_pd = _predict_box(season, box_d) if box_d else pd.Series(dtype=float)
    if box_o is not None and (box_po.notna().sum() if not box_po.empty else 0) < 500:
        box_po = _predict_box(season - 1, box_o); box_pd = _predict_box(season - 1, box_d)
    meta = _roster_meta(season)
    prev = POST.get(season - 1)
    repl_o, repl_d = 0.0, 0.0
    if prev is not None:
        low = prev[prev['share'] < 0.15]
        if len(low) and low['poss'].sum() > 0:
            w = low['poss'].clip(lower=1); repl_o, repl_d = float(np.average(low['OBPR'], weights=w)), float(np.average(low['DBPR'], weights=w))
    mu_o = np.zeros(obs.P); mu_d = np.zeros(obs.P)
    for i, pid in enumerate(obs.pids):
        b_o = float(box_po.get(pid, np.nan)) if not box_po.empty else np.nan
        b_d = float(box_pd.get(pid, np.nan)) if not box_pd.empty else np.nan
        has_box = np.isfinite(b_o) and np.isfinite(b_d)
        a_o, a_d = (b_o, b_d) if has_box else (repl_o, repl_d)

        if prev is not None and pid in prev.index:
            w = prev.at[pid, 'poss'] / (prev.at[pid, 'poss'] + RETURNER_POSS_K)
            mu_o[i] = w * RHO_O_PRIOR * prev.at[pid, 'OBPR'] + (1 - w) * a_o
            mu_d[i] = w * RHO_D_PRIOR * prev.at[pid, 'DBPR'] + (1 - w) * a_d
            continue

        ped = None
        try:
            m = meta.get(pid, {})
            name = obs.names.get(pid, '') or m.get('name', '')
            team = m.get('team') or obs.player_team.get(pid)
            ped = recruit_prior(season, name, team, pid=pid, height=m.get('height'), position=m.get('position'))
        except: pass

        if ped is not None and (abs(ped['o_raw']) > 1e-6 or abs(ped['d_raw']) > 1e-6):
            mu_o[i] = RECRUIT_PRIOR_BLEND * ped['o_raw'] + (1 - RECRUIT_PRIOR_BLEND) * a_o
            mu_d[i] = RECRUIT_PRIOR_BLEND * ped['d_raw'] + (1 - RECRUIT_PRIOR_BLEND) * a_d
        elif has_box: mu_o[i], mu_d[i] = b_o, b_d
        else: mu_o[i], mu_d[i] = repl_o, repl_d
    return mu_o, mu_d

def _fit_direct_team_subset(df_sub, lam=DIRECT_LAMBDA):
    rows = []
    for r in df_sub.itertuples():
        poss = r.poss if not pd.isna(r.poss) else 68.0
        if poss <= 0: continue
        hs = 0.0 if r.neutral else 1.0
        rows.append(dict(team=r.home, opp=r.away, eff=100*r.home_pts/poss, home_sign=hs))
        rows.append(dict(team=r.away, opp=r.home, eff=100*r.away_pts/poss, home_sign=-hs))
    tg = pd.DataFrame(rows)
    if tg.empty: return pd.DataFrame()
    teams = sorted(set(tg['team']) | set(tg['opp']))
    ti = {t: i for i, t in enumerate(teams)}; n = len(teams)
    mu_eff = float(tg['eff'].mean()); y = tg['eff'].values - mu_eff
    X = sparse.csr_matrix(
        (np.r_[np.ones(len(tg)), -np.ones(len(tg)), tg['home_sign'].values],
         (np.r_[np.arange(len(tg)), np.arange(len(tg)), np.arange(len(tg))],
          np.r_[tg['team'].map(ti).values, n+tg['opp'].map(ti).values, np.full(len(tg), 2*n)])),
        shape=(len(tg), 2*n+1))
    beta = np.linalg.solve((X.T @ X).toarray() + lam*np.eye(2*n+1), X.T @ y)
    tb = beta[:2*n]; tb[:n] -= tb[:n].mean(); tb[n:] -= tb[n:].mean()
    return pd.DataFrame({'team': teams, 'direct_net': tb[:n] + tb[n:]}).set_index('team')

def _precompute_direct_asof(season, refit_every=7):
    df = df_games[df_games['year']==season].copy()
    if 'date' not in df.columns or df['date'].isna().all(): return {}
    anchor = pd.Timestamp(season-1, 11, 1)
    df['_day'] = (df['date'] - anchor).dt.days
    out = {}
    for day in sorted(int(d) for d in df['_day'].dropna().unique())[::refit_every]:
        sub = df[df['_day'] < day]
        if len(sub) < 100: continue
        fitted = _fit_direct_team_subset(sub)
        if fitted.empty: continue
        for t, row in fitted.iterrows(): out[(t, day)] = float(row['direct_net'])
    return out

def fit_season(season, box_o, box_d, tau2_o=TAU2_O, tau2_d=TAU2_D, extra_pids=(), extra_teams=None, verbose=True):
    obs = build_obs(season, extra_pids=extra_pids, extra_teams=extra_teams)
    P = obs.P
    mu_o, mu_d = build_preseason_prior(season, obs, box_o, box_d, verbose=verbose)
    mu = np.concatenate([mu_o, mu_d])
    pv = np.concatenate([np.full(P, tau2_o), np.full(P, tau2_d)])
    A, b = _norm_eq(obs)
    po_cnt = np.bincount(obs.off.ravel(), weights=np.repeat(obs.w, 5), minlength=P)
    pd_cnt = np.bincount(obs.dfn.ravel(), weights=np.repeat(obs.w, 5), minlength=P)
    x = _solve(A, b, P, mu, pv, poss=np.concatenate([po_cnt, pd_cnt]))
    OBPR, DBPR = x[:P], x[P:2*P]
    poss = np.minimum(po_cnt, pd_cnt)
    team = np.array([obs.player_team.get(i, '') for i in range(P)])
    share = np.zeros(P)
    for t in set(team):
        m = (team == t) & (poss > 0)
        if m.sum() and poss[m].sum() > 0: share[m] = np.minimum(1.0, 5.0 * poss[m] / poss[m].sum())
        if (season - 1) in POST:
            prev = POST[season - 1]
            for i in range(P):
                if team[i] == t and poss[i] == 0 and obs.pids[i] in prev.index: share[i] = min(float(prev.at[obs.pids[i], 'share']), 1.0)
    df = pd.DataFrame({'name': [obs.names.get(i, obs.pids[i]) for i in range(P)], 'team': team, 'o': OBPR, 'd': DBPR,
                       'net': OBPR + DBPR, 'OBPR': OBPR, 'DBPR': DBPR, 'BPR': OBPR + DBPR, 'poss': poss, 'share': share}, index=pd.Index(obs.pids, name='id'))
    df.attrs.update(c=float(x[2*P]), hca=float(x[2*P+1]), n_stints=obs.n_rows, n_games=obs.n_games, season=season)
    return df

def aggregate_team(player_df):
    p = player_df[player_df['share'] > 0].copy()
    p['eff_share'] = p['share'] / p.groupby('team')['share'].transform('sum').replace(0, 1)
    p['eff_share'] = p['eff_share'].fillna(0.0)
    p['w_obpr'] = p['eff_share'] * p['OBPR'].fillna(0.0)
    p['w_dbpr'] = p['eff_share'] * p['DBPR'].fillna(0.0)
    p['w_bpr']  = p['eff_share'] * p['BPR'].fillna(0.0)

    # FIX: Add .reset_index() to the end of the return
    return p.groupby('team').agg(team_bpr=('w_bpr','sum'), team_obpr=('w_obpr','sum'), team_dbpr=('w_dbpr','sum'), n_players=('BPR','size'), total_poss=('poss','sum')).sort_values('team_bpr', ascending=False).reset_index()

def asof_bpr(season, refit_every=ASOF_REFIT_EVERY):
    if season in RATINGS_CACHE: return RATINGS_CACHE[season]
    obs = build_obs(season); P = obs.P
    past = [s for s in sorted(POST) if s < season]
    box_o, box_d = (_train_box(past, 'o'), _train_box(past, 'd')) if past else (None, None)
    mu_o, mu_d = build_preseason_prior(season, obs, box_o, box_d, verbose=False)
    mu = np.concatenate([mu_o, mu_d]); pv = np.concatenate([np.full(P, TAU2_O), np.full(P, TAU2_D)])
    date_map = dict(zip(df_games['game_id'], df_games['date']))
    anchor = pd.Timestamp(season-1, 11, 1)
    game_day = {gid: (date_map.get(gid, anchor) - anchor).days for gid in obs.game_ids}
    row_day = np.array([game_day[obs.game_ids[g]] for g in obs.game_idx])
    out = {}
    for day in sorted(set(int(d) for d in row_day))[::max(1, refit_every)] + [int(row_day.max()) + 1]:
        idx = np.where(row_day < day)[0]
        if len(idx) < 50: continue
        recency = 0.5 ** ((day - row_day[idx]) / ASOF_HALFLIFE_DAYS)
        A, b = _norm_eq_weighted(obs, idx, obs.w[idx] * recency)
        po, pd_ = _poss_counts(obs, idx, obs.w[idx])
        x = _solve(A, b, P, mu, pv, poss=np.concatenate([po, pd_]))
        OBPR, DBPR = x[:P], x[P:2*P]
        poss = np.minimum(po, pd_); team_arr = np.array([obs.player_team.get(i, '') for i in range(P)])
        for t in obs.teams:
            m = (team_arr == t) & (poss > 0)
            if m.sum() == 0 or poss[m].sum() == 0: out[(t, day)] = dict(net=np.nan); continue
            share = poss[m] / poss[m].sum()
            out[(t, day)] = dict(net=float((share * OBPR[m]).sum() + (share * DBPR[m]).sum()))
    RATINGS_CACHE[season] = out
    return out

def build_model_table(season):
    df = df_games[df_games['year']==season].copy()
    if df.empty or season not in RATINGS_CACHE: return df
    asof = RATINGS_CACHE[season]
    anchor = pd.Timestamp(season-1, 11, 1)
    date_map = dict(zip(df_games['game_id'], df_games['date']))
    df['day'] = [(date_map[g] - anchor).days if g in date_map and pd.notna(date_map[g]) else 120 for g in df['game_id']]
    asof_days = sorted(set(d for _, d in asof.keys()))
    def asof_lookup(team, day):
        avail = [d for d in asof_days if d <= day]
        return asof.get((team, max(avail)), {}).get('net', np.nan) if avail else np.nan
    df['net_h'] = [asof_lookup(t, d) for t, d in zip(df['home'], df['day'])]
    df['net_a'] = [asof_lookup(t, d) for t, d in zip(df['away'], df['day'])]
    df['hca'] = 1.0 - df['neutral'].astype(float); df['exp_poss'] = df['poss']
    df['net_x_tempo'] = (df['net_h'] - df['net_a']) * df['exp_poss'] / 100.0
    df['net_x_tempo_early'] = df['net_x_tempo'] * np.clip(1 - df['day']/EARLY_DAYS, 0, 1)
    if (season-1) in POST:
        prev_team = POST[season-1][POST[season-1]['team'].notna()].groupby('team').apply(lambda g: float((g['share'] * (g['OBPR'] + g['DBPR'])).sum()))
        df['rot_level'] = (df['home'].map(prev_team).fillna(0) - df['away'].map(prev_team).fillna(0)) * df['exp_poss'] / 100.0
    else: df['rot_level'] = 0.0
    direct_asof = _precompute_direct_asof(season)
    direct_days = sorted(set(d for _, d in direct_asof.keys()))
    def direct_lookup(team, day):
        avail = [d for d in direct_days if d <= day]
        return direct_asof.get((team, max(avail)), 0.0) if avail else 0.0
    dh = np.array([direct_lookup(t, d) for t, d in zip(df['home'], df['day'])])
    da = np.array([direct_lookup(t, d) for t, d in zip(df['away'], df['day'])])
    df['direct_net_diff'] = (dh - da) * df['exp_poss'] / 100.0
    df['target'] = (df['home_pts'] - df['away_pts']).clip(-MARGIN_CAP, MARGIN_CAP)
    return df.dropna(subset=['net_h','net_a']).reset_index(drop=True)

class MarginModel:
    def __init__(self, features, params, sigma):
        self.features, self.params, self.sigma = list(features), np.asarray(params, float), float(sigma)
    def predict(self, df): return df[self.features].values @ self.params

def fit_margin(df, features, last_season=None):
    df = df.dropna(subset=features + ['target'])
    if df.empty: return MarginModel(features, np.zeros(len(features)), 10.0)
    ref = df['year'].max() if last_season is None else last_season
    w = 0.85 ** (ref - df['year'].values.astype(float))
    X, y = df[features].values, df['target'].values
    params = np.linalg.solve((X.T*w) @ X + 1e-9*np.eye(len(features)), (X.T*w) @ y)
    sigma = float(np.sqrt((w * (y - X @ params)**2).sum() / w.sum()))
    return MarginModel(features, params, sigma)

