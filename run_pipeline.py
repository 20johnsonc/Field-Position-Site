    if rec.get('rating') is None: return None
    xv = np.r_[1.0, _recruit_features(rec, height=height, position=position)]
    return dict(o_raw=float(np.clip(xv @ m['b_o'], -RECRUIT_MAX_PRIOR, RECRUIT_MAX_PRIOR)), d_raw=float(np.clip(xv @ m['b_d'], -RECRUIT_MAX_PRIOR, RECRUIT_MAX_PRIOR)), share=float(np.clip(xv @ m['b_share'], 0, 0.8)))

