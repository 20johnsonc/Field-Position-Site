def norm_name(s):
    if not s or pd.isna(s): return ''
    toks = [t for t in re.sub(r"[.,'\-]", ' ', str(s).lower()).split() if t not in {'jr','sr','ii','iii','iv','v'}]
    return ' '.join(toks)
def _clean_key(name):
    parts = norm_name(name).split()
    if not parts: return ''
    return f'{_NICKNAMES.get(parts[0], parts[0])}_{parts[-1] if len(parts) > 1 else ""}'

def _wridge(F, y, w, pen):
    wn = w / w.mean(); G = F.T @ (F * wn[:, None]) + np.diag(pen) * (len(y) / 50.0)
    return np.linalg.solve(G, F.T @ (wn * y))

def _recruit_features(r, height=None, position=None):
    rt = r.get('rating')
    if rt is not None and rt > 1.5: rt = rt / 100.0
    z = (rt - 0.85) / 0.07 if (rt and np.isfinite(rt)) else 0.0
    rk = r.get('ranking')
    rank_score = max(0.0, 100.0 - rk) / 100.0 if (rk and rk > 0) else 0.0
    top_5  = 1.0 if (rk and 0 < rk <= 5) else 0.0
    top_15 = 1.0 if (rk and 5 < rk <= 15) else 0.0
    h = height if (height and np.isfinite(height)) else r.get('height')
    hz = (h - 78.0) / 3.5 if (h and np.isfinite(h)) else 0.0
    p = str(position or r.get('position')).upper() if position or r.get('position') else ''
    pg = 'Guard' if any(x in p for x in ['PG','SG','POINT','SHOOTING','GUARD']) else ('Big' if any(x in p for x in ['C','CENTER','PF','POWER']) else 'Wing')
    is_big = 1.0 if pg == 'Big' else 0.0
    return [z, rank_score, top_5, top_15, 1.0 if pg == 'Guard' else 0.0, is_big, hz, top_5 * is_big]

def get_recruit_model(season):
    if season in _RECRUIT_MODEL_CACHE: return _RECRUIT_MODEL_CACHE[season]
    train = [t for t in sorted(POST) if t <= season - 1 and RAW_RECRUITS.get(t - 1)]
    if not train: return None
    pairs = [(r.get('stars'), r.get('rating')) for t in train for r in (RAW_RECRUITS.get(t-1) or []) if r.get('stars') is not None and r.get('rating') is not None]
    s2r = {int(s): float(np.mean([a for b,a in pairs if b == s])) for s in sorted({int(b) for b,_ in pairs})} if pairs else {}
    Xs, ys, Xd, yo, yd, wd = [], [], [], [], [], []
    for t in train:
        post = POST[t]
        by_key = {}
        for idx, nm in zip(post.index, post['name']): by_key.setdefault(_clean_key(nm), []).append(idx)
        for r in (RAW_RECRUITS.get(t-1) or []):
            rt = r.get('rating')
            if (rt is None or not np.isfinite(rt)) and r.get('stars') in s2r: r = dict(r); r['rating'] = s2r[r['stars']]
            if r.get('rating') is None: continue
            x = _recruit_features(r)
            idx = str(r['athleteId']) if r.get('athleteId') and str(r['athleteId']) in post.index else None
            if not idx:
                c = by_key.get(_clean_key(r['name']), []); ct = [i for i in c if post.at[i,'team'] == r['team']]
                idx = ct[0] if ct else (c[0] if len(c) == 1 else None)
            Xs.append(x); ys.append(float(post.at[idx,'share']) if idx is not None else 0.0)
            if idx is not None and post.at[idx,'poss'] >= 100:
                Xd.append(x); yo.append(float(post.at[idx,'OBPR'])); yd.append(float(post.at[idx,'DBPR'])); wd.append(float(post.at[idx,'poss']))
    if len(ys) < 150: return None
    def _fit(X, y, w=None):
        Xa = np.column_stack([np.ones(len(X)), np.asarray(X, float)])
        return _wridge(Xa, np.asarray(y, float), np.ones(len(y)) if w is None else np.asarray(w, float), np.r_[1e-6, np.full(Xa.shape[1]-1, 1.5)])
    model = dict(s2r=s2r, b_share=_fit(Xs, ys), b_o=_fit(Xd, yo, wd) if len(yo)>=60 else np.zeros(len(Xs[0])+1), b_d=_fit(Xd, yd, wd) if len(yo)>=60 else np.zeros(len(Xs[0])+1))
    _RECRUIT_MODEL_CACHE[season] = model
    return model

