def _elapsed(period, sr, mode):
    p = int(period)
    if mode == 'game' and p <= 2: return 2400.0 - sr
    start = 1200.0*(p-1) if p <= 2 else 2400.0 + 300.0*(p-3)
    length = 1200.0 if p <= 2 else 300.0
    return start + max(length - sr, 0.0)

def build_stints(plays, home, away):
    P = [p for p in plays if p.get('period') and p.get('sr') is not None
         and p.get('hs') is not None and p.get('as_') is not None]
    P = sorted(P, key=lambda p: (int(p['period']), -p['sr']))
    if not P: return dict(stints=[], raw_plays=plays, total_seconds=0.0, names={}, teams={})
    mode = 'game' if any(int(p['period'])==1 and p['sr'] > 1260 for p in P) else 'period'
    names, teams, stints, cur = {}, {}, [], None
    for p in P:
        h = tuple(sorted(i for i, tm, _ in p['on'] if tm == home and i is not None))
        a = tuple(sorted(i for i, tm, _ in p['on'] if tm == away and i is not None))
        if len(h) != 5 or len(a) != 5: continue
        for i, tm, nm in p['on']:
            if i is not None: names[i], teams[i] = nm, tm
        t = max(_elapsed(p['period'], p['sr'], mode), cur['t1'] if cur else 0.0)
        if cur is None:
            cur = dict(key=(h,a), t0=0.0, h0=0.0, a0=0.0, t1=t, h1=p['hs'], a1=p['as_'])
        elif (h,a) == cur['key']:
            cur.update(t1=t, h1=max(p['hs'], cur['h1']), a1=max(p['as_'], cur['a1']))
        else:
            stints.append(cur)
            cur = dict(key=(h,a), t0=cur['t1'], h0=cur['h1'], a0=cur['a1'], t1=t,
                       h1=max(p['hs'], cur['h1']), a1=max(p['as_'], cur['a1']))
    if cur is not None: stints.append(cur)
    out = [(s['key'][0], s['key'][1], s['t1']-s['t0'], s['h1']-s['h0'], s['a1']-s['a0'], s['h0'], s['a0']) for s in stints]
    return dict(stints=out, raw_plays=plays, total_seconds=float(stints[-1]['t1']) if stints else 0.0, names=names, teams=teams)

