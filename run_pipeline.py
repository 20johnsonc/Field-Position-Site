def build_roster_universe(season):
    d1 = {t['school'] for t in (RAW_DIRECTORY.get(season, {}).get('teams') or []) if t.get('school')}
    current_rosters = {}
    pid_to_team = {}
    for tr in RAW_ROSTER.get(season, []):
        team = tr.get('team')
        if team in d1:
            for p in (tr.get('players') or []):
                pid = str(p.get('id'))
                if pid:
                    pid_to_team[pid] = team
                    current_rosters.setdefault(team, set()).add(_clean_key(p.get('name') or ''))
    for gid, rec in (PBP.get(season) or {}).items():
        for pid_raw, team in (rec.get('teams') or {}).items():
            if str(pid_raw) not in pid_to_team and team in d1: pid_to_team[str(pid_raw)] = team
    prev = POST.get(season - 1)
    if prev is not None:
        for pid, row in prev.iterrows():
            if row['poss'] <= 0 or str(pid) in pid_to_team: continue
            team_26 = row.get('team')
            if len(current_rosters.get(team_26, set())) >= 8: continue
            if team_26 in d1: pid_to_team[str(pid)] = team_26
    for x in (RAW_PORTAL.get(season) or []):
        if (x.get('elig') or '') == 'Withdrawn': continue
        dest = x.get('destination')
        if isinstance(dest, dict): dest = dest.get('name') or dest.get('school')
        if dest in d1:
            pid = str(x.get('athleteId') or '')
            if pid and pid not in pid_to_team: pid_to_team[pid] = dest
    return pid_to_team

