def build_adv_stats_from_store(store):
    """Rebuilds the shots, play types, and clutch DataFrames from the raw PBP store."""
    shots, pts, clutch = [], [], []

    for gid, rec in store.items():
        if not isinstance(rec, dict): continue
        for play in rec.get('raw_plays', []):
            is_shooting = play.get('shooting_play', False)
            is_scoring = play.get('scoring_play', False)
            ptype = play.get('play_type')
            pts_val = play.get('score_value', 0)

            # Get shooter ID (check shot_info first, then participants tuple)
            shooter_id = None
            si = play.get('shot_info')
            if is_shooting and si and si.get('shooter'):
                shooter_id = si['shooter'].get('id')

            if not shooter_id and play.get('participants'):
                # participants is a list of tuples like (id, name)
                shooter_id = play['participants'][0][0]

            if not shooter_id: continue

            # 1. Shots
            if is_shooting and si:
                loc = si.get('location') or {}
                shots.append({
                    'game_id': gid,
                    'player_id': str(shooter_id),
                    'team': play.get('team'),
                    'range': si.get('range', ''),
                    'made': bool(si.get('made', False)),
                    'x': loc.get('x'),
                    'y': loc.get('y')
                })

            # 2. Play Types (Scoring plays only)
            if is_scoring and ptype:
                pts.append({
                    'game_id': gid,
                    'player_id': str(shooter_id),
                    'team': play.get('team'),
                    'play_type': ptype,
                    'points': pts_val
                })

            # 3. Clutch (2nd half or OT, <= 5 mins, margin <= 5)
            period = play.get('period', 1)
            secs = play.get('sr', 9999)
            h_score = play.get('hs', 0)
            a_score = play.get('as_', 0)

            is_clutch_time = (period >= 2 and secs <= 300)
            is_clutch_margin = (abs(h_score - a_score) <= 5)

            if is_clutch_time and is_clutch_margin and is_shooting:
                made = si.get('made', False) if si else False
                clutch.append({
                    'game_id': gid,
                    'player_id': str(shooter_id),
                    'team': play.get('team'),
                    'made': bool(made),
                    'points': pts_val if made else 0
                })

    return pd.DataFrame(shots), pd.DataFrame(pts), pd.DataFrame(clutch)

